GLYPHS = {}
for ch, rows in _G.items():
    rows = rows.split("|")
    GLYPHS[ch] = rows

ALIASES = {"’": "'", "‘": "'", "“": '"', "”": '"', "–": "-"}


def glyph(ch):
    ch = ALIASES.get(ch, ch)
    if ch not in GLYPHS:
        raise KeyError(f"pixfont: no glyph for {ch!r}")
    return GLYPHS[ch]


def advance(ch):
    return len(glyph(ch)[0]) + 1


def width(s):
    """Width in font units (last glyph's trailing gap removed)."""
    return max(0, sum(advance(c) for c in s) - 1)


def glyph_path(ch):
    rows = glyph(ch)
    d = []
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            if row[x] == "#":
                x0 = x
                while x < len(row) and row[x] == "#":
                    x += 1
                d.append(f"M{x0} {y}h{x - x0}v1h{x0 - x}z")
            else:
                x += 1
    return "".join(d)
